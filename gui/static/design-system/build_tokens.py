"""Generate scoped CSS from the one canonical semantic registry."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def render():
    registry = json.loads((HERE / "tokens.json").read_text())
    lines = ["/* Generated by build_tokens.py from tokens.json; do not edit. */"]
    groups = [(".cosmos-ds", registry["typography"] | registry["layout"] | registry["themes"]["dark"])]
    groups += [(f'.cosmos-ds[data-theme="{theme}"]', values) for theme, values in registry["themes"].items()]
    for selector, values in groups:
        lines.append(selector + " {")
        lines += [f"  --ds-{key.replace('.', '-')}: {value};" for key, value in values.items()]
        lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = HERE / "tokens.css"
    value = render()
    if "--check" in sys.argv:
        assert target.read_text() == value, "Token CSS drift; regenerate from registry"
        print("Semantic token CSS matches registry")
    else:
        target.write_text(value)
